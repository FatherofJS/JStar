# Default language
DEFAULT_LANGUAGE = "en"

# Supported languages
SUPPORTED_LANGUAGES = ["en", "vi", "ja"]


def get_features(language: str = "en") -> list:
    """
    Get features for a specific language.
    
    Args:
        language: Language code (en, vi, ja)
    
    Returns:
        List of features for the requested language
    """
    if language in SUPPORTED_LANGUAGES:
        return FEATURES_DATA.get(language, FEATURES_DATA[DEFAULT_LANGUAGE])
    return FEATURES_DATA[DEFAULT_LANGUAGE]

